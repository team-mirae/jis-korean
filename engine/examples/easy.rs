//! Finds easy key sequences that type real Korean words: short runs on the number row (the
//! dedicated keys: 98 → 의외, 09 → 와의, 675 → 위웠), on the home row, or both. Each is typed
//! through the engine; a word counts when the corpus lexicon has seen it (count ≥ 20) or it's a
//! hanja-dictionary word. Writes docs/easy-words.md.
//! Usage: cargo run --release --example easy

use std::collections::{HashMap, HashSet};
use std::fmt::Write;
use std::sync::Arc;

use jis_korean::predict::{Kind, Predictor};
use jis_korean::travel::travel;
use jis_korean::{Dictionary, Engine, Key, Mods};

const MIN_COUNT: u32 = 20;

struct Found {
    keys: String,
    word: String,
    count: u32,
    travel: f64,
    top: bool,
}

fn main() {
    let root = env!("CARGO_MANIFEST_DIR");
    let read = |f: &str| std::fs::read_to_string(format!("{root}/predict/{f}")).unwrap();
    let model = std::fs::read(format!("{root}/predict/ranker.bin")).unwrap();
    let predictor = Arc::new(Predictor::parse(&model, &read("common-en.txt"), &read("common-ko.txt"), &read("english-nouns.txt")).unwrap());
    let dictionary = Arc::new(Dictionary::parse(&std::fs::read_to_string(format!("{root}/dict/hanja.tsv")).unwrap()));
    // Korean words with their counts in the corpora (hand-written ones count as common).
    let counts: HashMap<String, u32> = read("common-ko.txt")
        .lines()
        .filter(|l| !l.starts_with('#') && !l.trim().is_empty())
        .map(|l| match l.split_once('\t') {
            Some((w, n)) => (w.to_string(), n.trim().parse().unwrap_or(0)),
            None => (l.trim().to_string(), 1000),
        })
        .collect();
    let syllables = |w: &str| !w.is_empty() && w.chars().all(|c| ('가'..='힣').contains(&c));

    let number_row: Vec<char> = "1234567890".chars().collect();
    let home_row: Vec<char> = "asdfghjkl".chars().collect();
    let both: Vec<char> = number_row.iter().chain(&home_row).copied().collect();
    let sections: [(&str, &str, &[char], usize); 3] = [
        ("Number row only", "The dedicated keys: 1–5 ㅃ ㅉ ㄸ ㄲ ㅆ, 6–0 ㅟ ㅝ ㅚ ㅢ ㅘ, each vowel on an implied ㅇ.", &number_row, 4),
        ("Home row only", "ㅁ ㄴ ㅇ ㄹ ㅎ ㅗ ㅓ ㅏ ㅣ under the resting fingers, with the implied ㅇ.", &home_row, 4),
        ("Number row and home row", "Both rows mixed (at least one of each), up to four keys.", &both, 4),
    ];

    let mut out = String::new();
    writeln!(out, "# Easy key sequences that type Korean words\n").unwrap();
    writeln!(
        out,
        "Short runs of keys on the number row (JIS Korean's dedicated keys) and the home row that type real words, \
        thanks to the dedicated keys and the implied ㅇ: `98` is 의외, `09` is 와의, `675` is 위웠. Keys are the \
        letters and digits on the keys, no Shift. A word counts when the corpus lexicon has seen it at least \
        {MIN_COUNT} times or it's in the hanja dictionary (marked *dictionary*). **Top** is whether it's the top \
        prediction when typed alone. Travel is finger travel in key widths (`engine/src/travel.rs`).\n"
    )
    .unwrap();
    writeln!(
        out,
        "Pieces of words count only when they're words themselves: `675` types 위웠 (as in the end of 무서웠, 어려웠), \
        which isn't one, so it isn't listed. Each word appears once, with its easiest route.\n"
    )
    .unwrap();
    writeln!(out, "Generated by `cargo run --release --example easy` in `/engine`; don't edit by hand.\n").unwrap();
    // Each word once, by its easiest route, in the first section that has it.
    let mut words_seen: HashSet<String> = HashSet::new();
    let mut seen = HashSet::new();
    let mut total = 0;
    for (title, about, keys, max_len) in sections {
        let mut found: Vec<Found> = Vec::new();
        let mut sequence: Vec<usize> = vec![0];
        // Every sequence of 1..=max_len keys from the set, shortest first.
        'all: loop {
            let ks: String = sequence.iter().map(|&i| keys[i]).collect();
            let mixed_ok = title != "Number row and home row"
                || (ks.chars().any(|c| c.is_ascii_digit()) && ks.chars().any(|c| c.is_ascii_alphabetic()));
            if mixed_ok && !seen.contains(&ks) {
                let mut e = Engine::new();
                e.set_dictionary(dictionary.clone());
                let presses: Vec<Key> = ks
                    .chars()
                    .map(|c| Key::from_code(&if c.is_ascii_digit() { format!("Digit{c}") } else { format!("Key{}", c.to_ascii_uppercase()) }))
                    .collect();
                for &k in &presses {
                    e.key(k, Mods::NONE);
                }
                let word = e.preedit();
                let count = counts.get(&word).copied().unwrap_or(0);
                let in_dictionary = word.chars().count() >= 2 && !dictionary.lookup(&word).is_empty();
                if syllables(&word) && (count >= MIN_COUNT || in_dictionary) {
                    e.set_predictor(Some(predictor.clone()));
                    let top = e.predictions().first().is_some_and(|p| p.text == word && p.kind != Kind::Hanja);
                    found.push(Found { keys: ks.clone(), word, count, travel: travel(presses), top });
                    seen.insert(ks);
                }
            }
            // Next sequence: count up, growing the length when it wraps.
            let mut i = sequence.len();
            loop {
                if i == 0 {
                    if sequence.len() == max_len {
                        break 'all;
                    }
                    sequence = vec![0; sequence.len() + 1];
                    break;
                }
                i -= 1;
                sequence[i] += 1;
                if sequence[i] < keys.len() {
                    break;
                }
                sequence[i] = 0;
            }
        }
        // The easiest route per word (fewer keys, then less travel), and words already shown go.
        found.sort_by(|a, b| a.word.cmp(&b.word).then(a.keys.len().cmp(&b.keys.len())).then(a.travel.total_cmp(&b.travel)));
        found.dedup_by(|b, a| a.word == b.word);
        found.retain(|f| !words_seen.contains(&f.word));
        // Common words first; then fewer keys, then less travel.
        found.sort_by(|a, b| b.count.cmp(&a.count).then(a.keys.len().cmp(&b.keys.len())).then(a.travel.total_cmp(&b.travel)));
        let shown: Vec<&Found> = found.iter().take(if title == "Number row only" { usize::MAX } else { 80 }).collect();
        words_seen.extend(shown.iter().map(|f| f.word.clone()));
        total += shown.len();
        writeln!(out, "## {title}\n\n{about} {} found; {} shown.\n", found.len(), shown.len()).unwrap();
        writeln!(out, "| Keys | Word | Seen in corpora | Top | Travel |\n|---|---|---|---|---|").unwrap();
        for f in shown {
            let seen_in = if f.count >= MIN_COUNT { f.count.to_string() } else { "*dictionary*".to_string() };
            writeln!(out, "| `{}` | {} | {} | {} | {:.1} |", f.keys, f.word, seen_in, if f.top { "✓" } else { "" }, f.travel).unwrap();
        }
        writeln!(out).unwrap();
    }
    let path = format!("{root}/../docs/easy-words.md");
    std::fs::write(&path, out).unwrap();
    println!("{total} sequences written to docs/easy-words.md");
}

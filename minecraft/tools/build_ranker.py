# --- Hand-written lists (shared with the mod): frequent words the big lists miss or under-weight ---

LISTS = PREDICT


# common-*.txt: the hand-written list, then (below this line) words generated from the corpora.
GENERATED = "# --- generated by minecraft/tools/build_ranker.py from the corpora; edit above this line ---"


def read_list(name):
    """The hand-written part of a list."""
    with open(os.path.join(LISTS, name), encoding="utf-8") as f:
        text = f.read().split(GENERATED)[0]
    return [w.strip() for w in text.splitlines() if w.strip() and not w.startswith("#")]


def write_generated(name, words, directives=()):
    """Replaces the generated part of a list with `words`: (word, count) pairs, written as
    `word<TAB>count` (the predictor compares counts when two readings are both words)."""
    path = os.path.join(LISTS, name)
    with open(path, encoding="utf-8") as f:
        hand = f.read().split(GENERATED)[0].rstrip("\n")
    hand_words = set(read_list(name))
    extra = [f"{w}\t{n}" for w, n in words if w not in hand_words]
    with open(path, "w", encoding="utf-8") as f:
        f.write(hand + "\n\n" + GENERATED + "\n")
        f.writelines(f"{d}\n" for d in directives)
        f.write("\n".join(extra) + ("\n" if extra else ""))


COMMON_EN = read_list("common-en.txt")
COMMON_KO = read_list("common-ko.txt")

NOUN_WEIGHT = 3.0
# After these finals, these syllables on an implied ㅇ (산이, 말이) against the final moving onto
# the vowel (사니, 마리): their odds in the corpora are written to common-ko.txt for the predictor.
KEPT_FINALS = {"ㄴ": 4, "ㄹ": 8}  # final → its index in a syllable
KEPT_SYLLABLES = ["이", "의", "와", "에", "아"]
# Every business term trains with this weight and joins the lexicon, however often it's used.
BUSINESS_WEIGHT = 4.0
# The count every business term gets in the lexicon (equal weight), unless used more in chat.
BUSINESS_COUNT = 20
# A colloquial word joins the lexicon when it's seen this often in the training sentences. English
# needs 3+ letters: shorter generated words (al, ki) collide with Korean syllables (미, 아).
LEXICON_MIN_KO = 8
LEXICON_MIN_EN = 30
# One-syllable Korean words (내, 몇, 굿) need more: they're where Korean and English keys collide.
# A lone jamo (ㅁ, ㅜ) is never a word.
LEXICON_MIN_KO_SINGLE = 20


# --- Corpora (--corpora): colloquial sentences and business terms ---

def held_out(sentence):
    """1 in 10 sentences, picked by content: kept out of training and lexicons, for evaluation."""
    return int.from_bytes(hashlib.sha1(sentence.encode("utf-8")).digest()[:4], "big") % 10 == 0


def korean_sentences(corpora):
    with open(os.path.join(corpora, "nsmc-ratings.txt"), encoding="utf-8") as f:
        next(f)
        for line in f:
            parts = line.rstrip("\n").split("\t")
            if len(parts) == 3:
                yield parts[1]
    with open(os.path.join(corpora, "ChatbotData.csv"), encoding="utf-8") as f:
        for row in csv.reader(f):
            yield from row[:2]


def english_sentences(corpora):
    with bz2.open(os.path.join(corpora, "eng_sentences.tsv.bz2"), "rt", encoding="utf-8") as f:
        for line in f:
            parts = line.rstrip("\n").split("\t")
            if len(parts) == 3:
                yield parts[2]
    with open(os.path.join(corpora, "tm1-self-dialogs.json"), encoding="utf-8") as f:
        for dialog in json.load(f):
            for utterance in dialog.get("utterances", []):
                yield utterance.get("text", "")


KOREAN_TOKEN = re.compile(r"[가-힣ㄱ-ㅣ]+")
ENGLISH_TOKEN = re.compile(r"[A-Za-z]+")


def count_tokens(sentences, pattern, normalize):
    train, test = Counter(), Counter()
    for sentence in sentences:
        bucket = test if held_out(sentence) else train
        for token in pattern.findall(sentence):
            bucket[normalize(token)] += 1
    return train, test


def business_terms(corpora):
    """Korean standard terms and words, and English words of their English names and of FIBO's
    concept labels (lowercase labels only: capitalized ones are names of exchanges and firms)."""
    korean, english = set(), set()
    for name, column in (("std-terms.csv", "공통표준용어명"), ("std-words.csv", "공통표준단어명")):
        with open(os.path.join(corpora, name), encoding="utf-8-sig") as f:
            for row in csv.DictReader(f):
                term = row[column].strip()
                if re.fullmatch(r"[가-힣]{2,}", term):
                    korean.add(term)
                for word in ENGLISH_TOKEN.findall(row.get("공통표준단어 영문명", "") or ""):
                    if len(word) >= 3:
                        english.add(word.lower())
    with open(os.path.join(corpora, "fibo-labels.txt"), encoding="utf-8") as f:
        for label in f:
            label = label.strip()
            if label and label == label.lower():
                english.update(w for w in ENGLISH_TOKEN.findall(label) if len(w) >= 3)
    return sorted(korean), sorted(english)

PARTICLES = "은 는 이 가 을 를 에 에서 의 도 만 으로 로 와 과 이다 입니다 하다 했다 해요 하는 하고 적 들".split()

# --- Korean → 2-set keys ---

INITIAL_KEYS = dict(zip("ㄱㄲㄴㄷㄸㄹㅁㅂㅃㅅㅆㅇㅈㅉㅊㅋㅌㅍㅎ",
                        "r R s e E f a q Q t T d w W c z x v g".split()))
MEDIAL_KEYS = dict(zip("ㅏㅐㅑㅒㅓㅔㅕㅖㅗㅘㅙㅚㅛㅜㅝㅞㅟㅠㅡㅢㅣ",
                       "k o i O j p u P h hk ho hl y n nj np nl b m ml l".split()))
FINAL_KEYS = dict(zip("ㄱㄲㄳㄴㄵㄶㄷㄹㄺㄻㄼㄽㄾㄿㅀㅁㅂㅄㅅㅆㅇㅈㅊㅋㅌㅍㅎ",
                      "r R rt s sw sg e f fr fa fq ft fx fv fg a q qt t T d w c z x v g".split()))
JAMO_KEYS = {**INITIAL_KEYS, **MEDIAL_KEYS, **FINAL_KEYS}
INITIALS = "ㄱㄲㄴㄷㄸㄹㅁㅂㅃㅅㅆㅇㅈㅉㅊㅋㅌㅍㅎ"
MEDIALS = "ㅏㅐㅑㅒㅓㅔㅕㅖㅗㅘㅙㅚㅛㅜㅝㅞㅟㅠㅡㅢㅣ"
FINALS = " ㄱㄲㄳㄴㄵㄶㄷㄹㄺㄻㄼㄽㄾㄿㅀㅁㅂㅄㅅㅆㅇㅈㅊㅋㅌㅍㅎ"
# (previous medial, first key of the next vowel) pairs that would combine into a compound.
COMBINES = {("ㅗ", "k"), ("ㅗ", "o"), ("ㅗ", "l"), ("ㅜ", "j"), ("ㅜ", "p"), ("ㅜ", "l"), ("ㅡ", "l")}


def syllables(word):
    for ch in word:
        n = ord(ch) - 0xAC00
        if 0 <= n < 11172:
            yield INITIALS[n // 588], MEDIALS[n % 588 // 28], FINALS[n % 28].strip()
        elif ch in JAMO_KEYS:
            yield None, None, ch  # a bare jamo (ㅋㅋ)
        else:
            return


def implied_after_finals(counts):
    """log2 odds, per (final, syllable) of KEPT_FINALS × KEPT_SYLLABLES, of the final then that
    syllable on an implied ㅇ (산이, 말이) against an open syllable then the syllable the same keys
    make with the final moved onto the vowel (사니, 마리), over the corpus words. A syllable counts
    by its vowel, whatever final it has (기준입니다: 입 counts as 이). Add-one smoothed."""
    initial_index = {"ㄴ": 2, "ㄹ": 5}
    moved_form = {(f, s): chr(0xAC00 + initial_index[f] * 588 + (ord(s) - 0xAC00) % 588)
                  for f in KEPT_FINALS for s in KEPT_SYLLABLES}
    kept, moved = Counter(), Counter()

    def open_syllable(c):
        q = ord(c) - 0xAC00
        return chr(0xAC00 + q - q % 28) if 0 <= q < 11172 else c

    for word, n in counts.items():
        for prev, nxt in zip(word, word[1:]):
            nxt = open_syllable(nxt)
            p = ord(prev) - 0xAC00
            if not 0 <= p < 11172:
                continue
            final = p % 28
            for f, index in KEPT_FINALS.items():
                if final == index and nxt in KEPT_SYLLABLES:
                    kept[(f, nxt)] += n
            if final == 0:
                for key, onto in moved_form.items():
                    if nxt == onto:
                        moved[key] += n
    return {key: math.log2((kept[key] + 1) / (moved[key] + 1)) for key in moved_form}


def korean_keys(word, jis, rng=None):
    """The keys for a Korean word: explicit ㅇ (jis=False), how JIS Korean lets you type it most
    cheaply (jis=True), or, with `rng`, a mix of the valid ways syllable by syllable, as real
    typists do: 의 as 9, d9 or dml; 당신이 as ekdtlsL, ekdtlsll or ekdtlsdl. Keys are lowercased,
    so Shift+vowel reads as the vowel; dedicated number-row keys read as their 2-set keys, as the
    predictor maps them."""
    keys = []
    prev = None
    for initial, medial, final in syllables(word):
        if initial is None:
            keys.append(JAMO_KEYS[final])
            prev = None
            continue
        vowel = MEDIAL_KEYS[medial]
        if initial == "ㅇ" and jis:
            if prev and prev[2]:
                # After a final: the double press (말+ㅣ+ㅣ → 말이), Shift+vowel, or ㅇ typed.
                keys.append(rng.choice([vowel[0], "", "d"]) if rng else vowel[0])
            elif prev and (prev[1], vowel[0]) in COMBINES:
                # Would combine (오+ㅏ → 와): ㅇ typed, or Shift+vowel.
                keys.append(rng.choice(["d", ""]) if rng else "d")
            elif rng and rng.random() < 0.3:
                keys.append("d")  # ㅇ typed where it's implied
            # else: implied ㅇ, no key
        else:
            keys.append(INITIAL_KEYS[initial])
        keys.append(vowel)
        if final:
            keys.append(FINAL_KEYS[final])
        prev = (initial, medial, final)
    return "".join(keys).lower()


# --- Model: key trigrams over a-z, with start (^) and end ($) ---

A = 26
START = 26
END = 26


def code(c):
    return ord(c) - 97


def train(weighted_words):
    c3 = [0.0] * (27 * 27 * 27)
    c2 = [0.0] * (27 * 27)
    c1 = [0.0] * 27
    ctx2 = [0.0] * (27 * 27)
    ctx1 = [0.0] * 27
    for word, w in weighted_words:
        a = b = START
        for ch in word + "$":
            c = END if ch == "$" else code(ch)
            c3[(a * 27 + b) * 27 + c] += w
            ctx2[a * 27 + b] += w
            c2[b * 27 + c] += w
            ctx1[b] += w
            c1[c] += w
            a, b = b, c
    total = sum(c1)
    table = bytearray(27 * 27 * 27)
    for a in range(27):
        for b in range(27):
            for c in range(27):
                p1 = (c1[c] + 1) / (total + 27)
                p2 = c2[b * 27 + c] / ctx1[b] if ctx1[b] else p1
                p3 = c3[(a * 27 + b) * 27 + c] / ctx2[a * 27 + b] if ctx2[a * 27 + b] else p2
                p = 0.6 * p3 + 0.3 * p2 + 0.1 * p1
                table[(a * 27 + b) * 27 + c] = min(255, round(-math.log2(p) * 16))
    return table


def score(table, keys):
    """Average log2 probability per key (higher = more likely)."""
    a = b = START
    total = 0.0
    for ch in keys + "$":
        c = END if ch == "$" else code(ch)
        total -= table[(a * 27 + b) * 27 + c] / 16
        a, b = b, c
    return total / (len(keys) + 1)


def is_keys(s):
    return bool(s) and bool(re.fullmatch(r"[a-z]+", s))


def main():
    words_alpha = sys.argv[1]
    eval_korean = sys.argv[sys.argv.index("--eval-korean") + 1] if "--eval-korean" in sys.argv else None
    corpora = sys.argv[sys.argv.index("--corpora") + 1] if "--corpora" in sys.argv else None
    nouns = set()
    with open(sys.argv[sys.argv.index("--nouns") + 1], encoding="utf-8") as f:
        for line in f:
            if not line.startswith(" "):
                lemma = line.split(" ", 1)[0]
                if lemma.isalpha() and lemma.isascii():
                    nouns.add(lemma.lower())
    rng = random.Random(20261019)

    english = [w.strip() for w in open(words_alpha, encoding="utf-8") if w.strip()]
    readings = sorted({line.split("\t", 1)[0] for line in open(HANJA_TSV, encoding="utf-8")})
    rng.shuffle(english)
    rng.shuffle(readings)
    en_test, en_train = english[: len(english) // 10], english[len(english) // 10:]
    ko_test, ko_train = readings[: len(readings) // 10], readings[len(readings) // 10:]

    common_en = COMMON_EN
    common_ko = COMMON_KO

    en_data = [(w, NOUN_WEIGHT if w in nouns else 1.0) for w in en_train] + [(w, 200.0) for w in common_en]
    ko_words = [(w, 1.0) for w in ko_train] + [(w, 200.0) for w in common_ko]
    # Words with particles, so the model has seen eojeol endings.
    ko_words += [(w + rng.choice(PARTICLES), 1.0) for w in ko_train if rng.random() < 0.5]
    if corpora:
        ko_counts, ko_held = count_tokens(korean_sentences(corpora), KOREAN_TOKEN, lambda t: t)
        en_counts, en_held = count_tokens(english_sentences(corpora), ENGLISH_TOKEN, str.lower)
        biz_ko, biz_en = business_terms(corpora)
        print(f"corpora: {len(ko_counts)} Korean, {len(en_counts)} English word types; "
              f"business terms: {len(biz_ko)} Korean, {len(biz_en)} English")
        ko_words += [(w, math.log2(1 + n)) for w, n in ko_counts.items()]
        ko_words += [(w, BUSINESS_WEIGHT) for w in biz_ko]
        en_data += [(w, math.log2(1 + n)) for w, n in en_counts.items() if w.isascii()]
        en_data += [(w, BUSINESS_WEIGHT) for w in biz_en]
        # Lexicons: frequent colloquial words, and every business term (equal weight: membership).
        def lexicon(counts, minimum, min_len, business, single=None):
            words = {w: n for w, n in counts.items()
                     if (n >= minimum and len(w) >= min_len)
                     or (single and len(w) == 1 and "가" <= w <= "힣" and n >= single)}
            for w in business:
                words[w] = max(words.get(w, 0), counts.get(w, 0), BUSINESS_COUNT)
            return sorted(words.items(), key=lambda item: (-item[1], item[0]))
        lexicon_ko = lexicon(ko_counts, LEXICON_MIN_KO, 2, biz_ko, LEXICON_MIN_KO_SINGLE)
        lexicon_en = lexicon(en_counts, LEXICON_MIN_EN, 3, biz_en)
        odds = implied_after_finals(ko_counts)
        print("implied ㅇ after a kept final, log2 odds:", {f + s: round(v, 2) for (f, s), v in odds.items()})
        # "#!" lines: read by the predictor, skipped as comments by every other reader.
        write_generated("common-ko.txt", lexicon_ko, [f"#!implied-after {f} {s} {v:.3f}" for (f, s), v in odds.items()])
        write_generated("common-en.txt", lexicon_en)
        print(f"lexicons: {len(lexicon_ko)} Korean, {len(lexicon_en)} English generated words")
        # Held-out words with counts, for engine/examples/sxs.rs (gitignored with the corpora).
        for name, held in (("heldout-ko.txt", ko_held), ("heldout-en.txt", en_held)):
            with open(os.path.join(corpora, name), "w", encoding="utf-8") as f:
                f.write("".join(f"{w}\t{n}\n" for w, n in held.most_common()))
    ko_data = []
    route_rng = random.Random(20261020)
    # Every word as typed every jamo, the cheapest way, and two mixes of the valid ways.
    routes = [(False, None, 0.25), (True, None, 0.35), (True, route_rng, 0.2), (True, route_rng, 0.2)]
    for w, weight in ko_words:
        for jis, rng, share in routes:
            k = korean_keys(w, jis, rng)
            if is_keys(k):
                ko_data.append((k, weight * share))

    en_table = train(en_data)
    ko_table = train(ko_data)

    def accuracy(name, keys_list, want_korean):
        keys_list = [k for k in keys_list if is_keys(k)]
        right = sum((score(ko_table, k) > score(en_table, k)) == want_korean for k in keys_list)
        print(f"  {name:<34} {right / len(keys_list):6.1%} of {len(keys_list)}")

    print("accuracy (held out):")
    accuracy("English words (dwyl)", en_test, False)
    accuracy("  of which nouns (WordNet)", [w for w in en_test if w in nouns], False)
    accuracy("  of which non-nouns", [w for w in en_test if w not in nouns], False)
    accuracy("English common words (trained)", common_en, False)
    accuracy("Korean words, explicit ㅇ", [korean_keys(w, False) for w in ko_test], True)
    accuracy("Korean words, JIS Korean typing", [korean_keys(w, True) for w in ko_test], True)
    mix = random.Random(7)
    accuracy("Korean words, mixed routes", [korean_keys(w, True, mix) for w in ko_test], True)
    if eval_korean:
        eojeols = [t for t in re.findall(r"[가-힣]+", open(eval_korean, encoding="utf-8").read())]
        accuracy("Korean text eojeols, explicit ㅇ", [korean_keys(w, False) for w in eojeols], True)
        accuracy("Korean text eojeols, JIS typing", [korean_keys(w, True) for w in eojeols], True)

    # The noun lexicon for the predictor's exact-word bonus: WordNet noun lemmas, 3+ letters (short
    # "nouns" like al would steal Korean syllables such as 미).
    with open(os.path.join(PREDICT, "english-nouns.txt"), "w", encoding="utf-8") as f:
        f.write("# English nouns in normalized form (Princeton WordNet 3.0 index.noun lemmas, 3+ letters).\n")
        f.write("# Generated by minecraft/tools/build_ranker.py; license in LICENSE-wordnet.txt.\n")
        f.write("\n".join(sorted(w for w in nouns if len(w) >= 3)) + "\n")

    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "wb") as f:
        f.write(b"JKRK")
        f.write(struct.pack(">HH", 1, 27))
        f.write(en_table)
        f.write(ko_table)
    print(f"{OUT}: {os.path.getsize(OUT)} bytes")

    for w in ["hello", "minecraft", "diamond", "gg", "ok", "lol"]:
        print(f"  {w:<12} en={score(en_table, w):6.2f} ko={score(ko_table, w):6.2f}")
    for w in ["안녕하세요", "말이", "다이아", "ㅋㅋㅋ", "사람이", "학교에서"]:
        k = korean_keys(w, True)
        print(f"  {w:<8} {k:<14} en={score(en_table, k):6.2f} ko={score(ko_table, k):6.2f}")


main()

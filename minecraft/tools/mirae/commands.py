"""Lists every command and alias of the Mirae plugin (미래서버), for the Minecraft mod's ranker.

The plugin (https://github.com/themrsung/Mirae, MIT, Copyright (c) 2025-2026 Min Jun Sung) registers
its commands in Commands.getCommands(); each command class names itself with super("name") and its
aliases with setAliases(List.of(...)). This script reads those, verbatim, from a checkout of the
plugin and writes commands.txt: one name per line, marked en (Latin) or ko (Hangul), with the
command it belongs to. Command names are public source, so commands.txt is committed (unlike the
chat logs).

Usage: python3 -I commands.py <Mirae checkout>   (writes commands.txt next to this script)
"""

import re
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent


def main():
    root = Path(sys.argv[1])
    source = root / "src/main/java/com/themrsung/mirae/command"
    registered = re.findall(r"new (\w+Command)\(\)", (source / "Commands.java").read_text(encoding="utf-8"))
    files = {p.stem: p for p in source.rglob("*Command.java")}
    commit = subprocess.run(["git", "-C", str(root), "log", "-1", "--format=%H %cs"],
                            capture_output=True, text=True).stdout.strip()

    rows = []
    for cls in registered:
        text = files[cls].read_text(encoding="utf-8")
        name = re.search(r'super\(\s*"([^"]+)"', text)
        if not name:
            continue
        aliases = re.search(r"setAliases\(\s*List\.of\((.*?)\)\s*\)", text, re.S)
        words = [name[1]] + (re.findall(r'"([^"]+)"', aliases[1]) if aliases else [])
        for word in dict.fromkeys(words):
            rows.append((word, "ko" if re.search(r"[가-힣ㄱ-ㅎㅏ-ㅣ]", word) else "en", name[1]))

    out = HERE / "commands.txt"
    out.write_text(
        "# Commands and aliases of the Mirae plugin (https://github.com/themrsung/Mirae, MIT,\n"
        "# Copyright (c) 2025-2026 Min Jun Sung), verbatim, as registered in Commands.getCommands().\n"
        f"# Generated by minecraft/tools/mirae/commands.py from commit {commit}.\n"
        "# name<TAB>language<TAB>command\n"
        + "".join(f"{w}\t{lang}\t{cmd}\n" for w, lang, cmd in rows),
        encoding="utf-8",
    )
    langs = [lang for _, lang, _ in rows]
    print(f"{len(registered)} commands, {len(rows)} names and aliases ({langs.count('en')} en, {langs.count('ko')} ko) -> {out}")


if __name__ == "__main__":
    main()
